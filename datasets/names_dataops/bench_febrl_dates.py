"""Does `refutes_below` on a date of birth earn its place? Febrl 4 answers.

The question has one measurement for it and one against. The Parrish linkage set
showed a small precision gain (0.9962 -> 1.0000). NCVR showed nothing at all,
and the reason was structural: NCVR carries a birth *year*, which scores 1.0 or
0.0 with no middle, so the near-miss band refutation acts on cannot exist there.

Febrl 4 is the dataset that can settle it, for three reasons NCVR could not meet:

* **Full dates.** `19151111`, not `1915`.
* **Real corruption, not an assumed rate.** The generator introduced the errors,
  so the disagreement rate is a property of the data rather than something this
  script chose. 444 of 5,000 true pairs (8.9%) disagree on date of birth, and
  **52 of them land in the 0.35 near-miss band**.
* **Complete truth.** Every pair not in the mapping is a known non-match, so
  false merges are countable rather than inferred.

What it still is not
--------------------
Synthetic. The errors were generated by a program that had a model of how people
mistype, which is not the same as how people actually mistype. A result here is
evidence that the mechanism works as designed, not that the design matches
reality.

`soc_sec_id` is deliberately excluded. With it, precision is already 1.0000 and
nothing a date does can be seen. The interesting arm is the one where the engine
has only name and address, which is where most real linkage lives.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_REPO = _HERE.parents[1]
sys.path.insert(0, str(_REPO / "packages" / "arche-core" / "src"))
sys.path.insert(0, str(_HERE))

from arche.resolve import crosswalk  # noqa: E402
from arche.resolve._matcher import compare_dates  # noqa: E402
from bench_febrl import _fetch, _truth_key  # noqa: E402

OUT = _HERE / "bench_febrl_dates_result.json"
FILES = ("dataset4a.csv", "dataset4b.csv")

BASE = [
    {"field": "name", "kind": "name", "weight": 2.0},
    {"field": "name", "kind": "tftoken", "weight": 2.0},
    {"field": "address", "kind": "address", "weight": 1.0},
]
WITH_DATE = [*BASE, {"field": "birth_date", "kind": "date", "weight": 2.0}]
REFUTING = [*BASE, {"field": "birth_date", "kind": "date", "weight": 2.0,
                    "refutes_below": 0.5}]


def _record(row: dict) -> dict:
    addr = " ".join(x for x in (row.get("street_number"), row.get("address_1"),
                                row.get("address_2"), row.get("suburb"),
                                row.get("postcode"), row.get("state")) if x)
    return {"id": row["rec_id"],
            "name": " ".join(x for x in (row.get("given_name"),
                                         row.get("surname")) if x),
            "address": addr,
            "birth_date": row.get("date_of_birth", "")}


def score(a_rows, b_rows, comparators, label) -> dict:
    res = crosswalk([_record(r) for r in a_rows], [_record(r) for r in b_rows],
                    entity="person", id_field="id", comparators=comparators)
    n_true = len({_truth_key(r["rec_id"]) for r in a_rows}
                 & {_truth_key(r["rec_id"]) for r in b_rows})

    matched, surfaced, fp, flagged = set(), set(), 0, 0
    for e in res["matches"]:
        correct = _truth_key(e["a_id"]) == _truth_key(e["b_id"])
        if "birth_date_conflict" in (e.get("evidence") or {}):
            flagged += 1
        if e["decision"] == "match":
            if correct:
                matched.add(_truth_key(e["a_id"]))
            else:
                fp += 1
        if e["decision"] in ("match", "review") and correct:
            surfaced.add(_truth_key(e["a_id"]))

    tp = len(matched)
    return {
        "arm": label, "pairs_truth": n_true,
        "true_merges": tp, "false_merges": fp,
        "precision": round(tp / (tp + fp), 4) if tp + fp else 0.0,
        "auto_resolved": round(tp / n_true, 4) if n_true else 0.0,
        "surfaced": round(len(surfaced) / n_true, 4) if n_true else 0.0,
        # The diagnostic NCVR needed: refutation can only act on a pair whose
        # other evidence kept it alive despite the date disagreeing.
        "conflicts_flagged": flagged,
    }


def main() -> int:
    a_rows, b_rows = (list(_fetch(f)) for f in FILES)
    print(f"  Febrl 4: {len(a_rows):,} originals x {len(b_rows):,} duplicates\n",
          flush=True)

    by_a = {_truth_key(r["rec_id"]): r for r in a_rows}
    truth_pairs = [(by_a[_truth_key(r["rec_id"])], r)
                   for r in b_rows if _truth_key(r["rec_id"]) in by_a]
    buckets: dict[float, int] = {}
    for x, y in truth_pairs:
        v = compare_dates(x["date_of_birth"], y["date_of_birth"])
        buckets[v] = buckets.get(v, 0) + 1
    print("  What the date comparator sees on the 5,000 TRUE pairs:")
    for v in sorted(buckets, reverse=True):
        tag = {1.0: "agree", 0.35: "one keying slip", 0.0: "disagree or absent"}
        print(f"    {v:>4}  {buckets[v]:>5}  {tag.get(v, '')}")
    print("  The 0.35 row is the whole question. NCVR could not produce one.\n",
          flush=True)

    results = []
    for label, spec in (("name + address", BASE),
                        ("+ date, weighted", WITH_DATE),
                        ("+ date, refuting", REFUTING)):
        r = score(a_rows, b_rows, spec, label)
        results.append(r)
        print(f"  {label:<20} true {r['true_merges']:>5}  false {r['false_merges']:>5}"
              f"  precision {r['precision']:.4f}  auto {r['auto_resolved']:.4f}"
              f"  surfaced {r['surfaced']:.4f}  refuted {r['conflicts_flagged']}",
              flush=True)

    OUT.write_text(json.dumps({
        "benchmark": "Febrl 4, refutation on a full date of birth",
        "why_this_dataset": (
            "full dates, generator-introduced corruption at a rate the data "
            "supplies rather than the script assuming, and complete truth"
        ),
        "what_it_is_not": "synthetic; the errors match a generator's model of typing",
        "soc_sec_id": "excluded on purpose; with it precision is already 1.0000",
        "true_pair_date_scores": {str(k): v for k, v in sorted(buckets.items())},
        "arms": results,
    }, indent=2), encoding="utf-8")
    print(f"\n  -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
